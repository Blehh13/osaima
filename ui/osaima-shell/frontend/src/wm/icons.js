/** An icon as an SVG string. Decorative by default (hidden from screen readers). */
export function icon(name, size = 16, cls = '') {
  const body = P[name] || P.info;
  return `<svg class="ui-icon${cls ? ' ' + cls : ''}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${body}</svg>`;
}

function el(tag, cls, text) {
  const e = document.createElement(tag);
  if (cls) e.className = cls;
  if (text !== undefined) e.textContent = text;
  return e;
}

/** An icon as an element, for append(). */
export function iconEl(name, size = 16, cls = '') {
  const t = document.createElement('template');
  t.innerHTML = icon(name, size, cls);
  return t.content.firstChild;
}

/** Puts an icon in front of a button's text: [icon] Label. */
export function withIcon(node, name, label, size = 16) {
  node.replaceChildren(iconEl(name, size), el('span', 'ui-label', label));
  return node;
}

/** An icon-only button with an accessible name and a tooltip. */
export function iconButton(name, label, cls = 'ui-iconbtn', size = 18) {
  const b = el('button', cls);
  b.type = 'button';
  b.setAttribute('aria-label', label);
  b.title = label;
  b.append(iconEl(name, size));
  return b;
}

/** A small status chip: tone is ok | warn | bad | info | muted. */
export function chip(text, iconName = null, tone = 'muted', cls = '') {
  const c = el('span', `ui-chip ui-chip-${tone}${cls ? ' ' + cls : ''}`);
  if (iconName) c.append(iconEl(iconName, 14));
  c.append(el('span', null, text));
  return c;
}

// one tip open at a time; a click elsewhere or Esc closes it
let tipSeq = 0;
let openTip = null;
const closeTip = () => {
  if (!openTip) return;
  openTip.classList.remove('is-open');
  openTip.querySelector('.ui-tip-btn')?.setAttribute('aria-expanded', 'false');
  openTip = null;
};
if (typeof document !== 'undefined') {
  document.addEventListener('click', (e) => { if (openTip && !openTip.contains(e.target)) closeTip(); });
  document.addEventListener('keydown', (e) => { if (e.key === 'Escape') closeTip(); });
}

/**
 * The explanation behind an (i) button: shown on hover, on keyboard focus and
 * on click (so it works without a mouse too). align: 'start' | 'end'.
 */
export function infoTip(text, label = 'More info', align = 'start') {
  const wrap = el('span', 'ui-tip' + (align === 'end' ? ' ui-tip-end' : ''));
  const b = el('button', 'ui-tip-btn');
  b.type = 'button';
  b.setAttribute('aria-label', label);
  b.setAttribute('aria-expanded', 'false');
  b.append(iconEl('info', 15));
  const bubble = el('span', 'ui-tip-bubble', text);
  bubble.id = `ui-tip-${++tipSeq}`;
  bubble.setAttribute('role', 'tooltip');
  b.setAttribute('aria-describedby', bubble.id);
  b.addEventListener('click', (e) => {
    e.stopPropagation();
    const open = !wrap.classList.contains('is-open');
    closeTip();
    if (open) { wrap.classList.add('is-open'); b.setAttribute('aria-expanded', 'true'); openTip = wrap; }
  });
  wrap.append(b, bubble);
  return wrap;
}

/** An empty state: one icon and one line (and an optional action). */
export function emptyState(iconName, line, action = null) {
  const box = el('div', 'ui-empty');
  box.append(el('span', 'ui-empty-icon'), el('p', 'ui-empty-text', line));
  box.firstChild.append(iconEl(iconName, 22));
  if (action) box.append(action);
  return box;
}

/** Skeleton rows while something loads (announced as busy). */
export function skeleton(rows = 3, cls = '') {
  const box = el('div', 'ui-skel' + (cls ? ' ' + cls : ''));
  box.setAttribute('aria-busy', 'true');
  box.setAttribute('aria-label', 'Loading');
  for (let i = 0; i < rows; i++) {
    const r = el('div', 'ui-skel-row');
    r.style.setProperty('--w', `${[92, 76, 84, 64, 88][i % 5]}%`);
    box.append(r);
  }
  return box;
}

/** A "Details" disclosure: summary line, content hidden until opened. */
export function details(summary, ...content) {
  const d = el('details', 'ui-details');
  const s = el('summary', 'ui-details-sum');
  s.append(iconEl('chevron-right', 14, 'ui-details-chev'), el('span', null, summary));
  d.append(s, ...content);
  return d;
}
